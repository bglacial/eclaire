import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const url = 'http://localhost:5173/design/refonte/';
let checks = 0;
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${url}app.html`);
  await page.waitForFunction(() => window.prototypeReady, { timeout: 60000 });
  await page.getByRole('button', { name: 'Éclairer la route' }).click();
  await page.getByRole('button', { name: 'Étapes', exact: true }).waitFor();
  const baseline = await page.evaluate(() => window.eclaireDemo.result.length);
  assert(baseline > 0); checks++;
  await page.getByRole('button', { name: 'Étapes', exact: true }).click();
  await page.getByLabel('Ajouter une étape').fill('Parking Hôtel de Ville');
  await page.getByRole('button', { name: 'Ajouter', exact: true }).click();
  assert.equal(await page.locator('.stop').count(), 1); checks++;
  await page.getByRole('button', { name: 'Annuler', exact: true }).click();
  assert.equal(await page.evaluate(() => window.eclaireDemo.stops.length), 0); checks++;
  assert.equal(await page.evaluate(() => window.eclaireDemo.result.length), baseline); checks++;
  await page.getByRole('button', { name: 'Lieux sur la route' }).click();
  assert.equal(await page.locator('.place').count(), 3); checks++;
  await page.locator('.place button').first().click();
  assert.equal(await page.evaluate(() => window.eclaireDemo.stops.length), 1); checks++;
  await page.getByRole('button', { name: 'Simuler le guidage' }).click();
  assert.equal(await page.locator('#follow').isVisible(), false); checks++;
  await page.locator('#zoom-in').click();
  await page.waitForFunction(() => !document.getElementById('follow').hidden);
  assert.equal(await page.locator('#follow').isVisible(), true); checks++;
  await page.locator('#follow').click();
  assert.equal(await page.locator('#follow').isVisible(), false); checks++;
  const instruction = await page.locator('.turn-road').innerText();
  await page.getByRole('button', { name: 'Avancer la simulation' }).click();
  assert.notEqual(await page.locator('.turn-road').innerText(), instruction); checks++;
  await page.getByLabel('Passer en mode nuit').click();
  assert.equal(await page.locator('html').getAttribute('data-night'), ''); checks++;
  await page.goto(url);
  const frame = page.frameLocator('#prototype');
  await frame.getByRole('button', { name: 'Étapes', exact: true }).waitFor({ timeout: 60000 });
  await page.getByRole('button', { name: 'Point zéro', exact: true }).click();
  await frame.getByRole('heading', { name: 'Point zéro', exact: true }).waitFor(); checks++;
  await page.getByLabel('Explorer les choix de conception').fill('signal');
  assert.equal(await page.locator('#commands button').count(), 1); checks++;
  await page.locator('#commands button').click();
  assert.match(await page.locator('#choice-title').innerText(), /Dire ce que/); checks++;
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false); checks++;
    await page.screenshot({ path: `/private/tmp/eclaire-refonte-${width}.png`, fullPage: false });
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(`${url}app.html?mode=result`);
  await page.waitForFunction(() => window.prototypeReady);
  await page.getByRole('button', { name: 'Rejouer', exact: true }).click();
  assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0); checks++;
  assert.deepEqual(errors, []); checks++;
  console.log(`${checks} contrôles du prototype réussis : calcul, annulation, pause, guidage, suivi, thème, intégration, recherche, formats et mouvements réduits.`);
} finally { await browser.close(); }
